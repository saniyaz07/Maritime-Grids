class VirtualVesselSimulator:
    """
    Native real-time virtual maritime simulator.
    Simulates vessel kinematics, environmental forces (waves, wind, current drift),
    hydrodynamic resistance, fuel consumption, and battery state of charge.
    Produces Signal Agent decision-support alerts and feeds the TelemetryGateway.
    """

    def __init__(
        self,
        vessel_id: str = "VESSEL_OSV_01",
        ship_type: str = "Oil Service Boat",
        route_id: str = "Escravos-Lagos",
        gateway: Optional[Any] = None,
        initial_fuel_liters: float = 25000.0,
        initial_battery_soc_pct: float = 85.0,
        weather_provider: Optional[Any] = None,
        weather_refresh_interval_seconds: float = 300.0,
    ) -> None:
        self.gateway = gateway
        self.weather_provider = weather_provider
        self.weather_refresh_interval_seconds = max(10.0, weather_refresh_interval_seconds)
        self._lock = threading.RLock()
        self._stop_event = threading.Event()
        self._thread: Optional[threading.Thread] = None
        self._weather_thread: Optional[threading.Thread] = None
        self._last_weather_fetch_mono: Optional[float] = None
        self._last_weather_coords: Optional[Tuple[float, float]] = None

        # Energy Estimator for physical resistance & SFOC scaling
        self.energy_estimator = VirtualEnergyEstimator(
            ship_type=ship_type,
            initial_fuel_liters=initial_fuel_liters,
            initial_battery_soc_pct=initial_battery_soc_pct,
        )

        # Canonical Simulation State
        self.state = VirtualVesselState(
            vessel_id=vessel_id,
            ship_type=ship_type,
            route_id=route_id,
            status=SimulationStatus.IDLE,
            latitude=5.58,
            longitude=5.18,
            heading_deg=285.0,
            course_over_ground_deg=285.0,
            speed_over_ground_knots=12.0,
            speed_through_water_knots=12.0,
            target_speed_knots=12.0,
            throttle_pct=75.0,
            engine_state="OFF",
            engine_rpm=0.0,
            engine_load_pct=0.0,
            rated_engine_power_kw=float(self.energy_estimator.profile.get("engine_power_kw", 4500.0)),
            fuel_remaining_liters=initial_fuel_liters,
            fuel_consumption_rate_lph=142.5,
            fuel_consumed_liters=0.0,
            battery_soc_pct=initial_battery_soc_pct,
            battery_energy_kwh=(initial_battery_soc_pct / 100.0) * self.energy_estimator.battery_capacity_kwh,
            distance_travelled_nm=0.0,
            distance_remaining_nm=250.0,
            route_progress_pct=0.0,
            voyage_elapsed_seconds=0,
            travelled_track=[[5.58, 5.18]],
        )

        # Calculate initial evaluations
        self._update_evaluations()

    def attach_weather_provider(self, provider: Any) -> None:
        """Attaches a WeatherProvider and triggers an initial non-blocking weather refresh."""
        with self._lock:
            self.weather_provider = provider
        if self.state.ocean_conditions.environmental_mode == "AUTOMATIC_FORECAST":
            threading.Thread(target=self.fetch_and_update_weather, daemon=True).start()

    @property
    def status(self) -> SimulationStatus:
        return self.state.status

    @property
    def latitude(self) -> float:
        return self.state.latitude

    @latitude.setter
    def latitude(self, val: float) -> None:
        self.state.latitude = val

    @property
    def longitude(self) -> float:
        return self.state.longitude

    @longitude.setter
    def longitude(self, val: float) -> None:
        self.state.longitude = val

    @property
    def fuel_remaining_liters(self) -> float:
        return self.state.fuel_remaining_liters

    @fuel_remaining_liters.setter
    def fuel_remaining_liters(self, val: float) -> None:
        self.state.fuel_remaining_liters = val

    @property
    def battery_soc_pct(self) -> float:
        return self.state.battery_soc_pct

    @battery_soc_pct.setter
    def battery_soc_pct(self, val: float) -> None:
        self.state.battery_soc_pct = val
        batt_cap = self.energy_estimator.battery_capacity_kwh
        self.state.battery_energy_kwh = round((val / 100.0) * batt_cap, 2)

    def start(self) -> VirtualVesselState:
        """Starts continuous simulation execution."""
        with self._lock:
            self.state.status = SimulationStatus.RUNNING
            self.state.engine_state = "ON"
            self.state.timestamp_utc = datetime.now(timezone.utc).isoformat()
            self._recalculate_physics()
            self._publish_frame()

            # Ensure background thread is running
            if self._thread is not None and self._thread.is_alive():
                self._stop_event.set()
                self._thread.join(timeout=0.3)

            self._stop_event.clear()
            self._thread = threading.Thread(
                target=self._run_loop,
                daemon=True,
                name="VirtualVesselSimulatorThread",
            )
            self._thread.start()

            # Ensure background weather refresh thread is running if provider is attached
            if self.weather_provider is not None:
                if self._weather_thread is None or not self._weather_thread.is_alive():
                    self._weather_thread = threading.Thread(
                        target=self._weather_refresh_loop,
                        daemon=True,
                        name="VirtualVesselWeatherRefreshThread",
                    )
                    self._weather_thread.start()

            return self.get_state()

    def pause(self) -> VirtualVesselState:
        """Pauses simulation advancement."""
        with self._lock:
            self.state.status = SimulationStatus.PAUSED
            self.state.engine_state = "OFF"
            self._stop_event.set()
            self._recalculate_physics()
            return self.get_state()

    def reset(self) -> VirtualVesselState:
        """Resets virtual vessel simulation to initial departure state at Escravos."""
        with self._lock:
            self.state.status = SimulationStatus.IDLE
            self.state.engine_state = "OFF"
            self._stop_event.set()
            self.state.latitude = 5.58
            self.state.longitude = 5.18
            self.state.heading_deg = 285.0
            self.state.course_over_ground_deg = 285.0
            self.state.speed_through_water_knots = 12.0
            self.state.speed_over_ground_knots = 12.0
            self.state.target_speed_knots = 12.0
            self.state.throttle_pct = 75.0
            self.state.fuel_remaining_liters = 25000.0
            self.state.fuel_consumed_liters = 0.0
            self.state.battery_soc_pct = 85.0
            self.state.battery_energy_kwh = (85.0 / 100.0) * self.energy_estimator.battery_capacity_kwh
            self.state.distance_travelled_nm = 0.0
            self.state.distance_remaining_nm = 250.0
            self.state.route_progress_pct = 0.0
            self.state.voyage_elapsed_seconds = 0
            self.state.voyage_elapsed_formatted = "00:00:00"
            self.state.timestamp_utc = datetime.now(timezone.utc).isoformat()
            self.state.travelled_track = [[5.58, 5.18]]
            self.state.ocean_conditions = OceanConditions()
            self.energy_estimator.reset_state(initial_fuel_liters=25000.0, initial_battery_soc_pct=85.0)
            self._last_weather_fetch_mono = None
            self._last_weather_coords = None

            self._recalculate_physics()

        # If weather provider is configured, trigger initial weather refresh in background
        if self.weather_provider is not None:
            threading.Thread(target=self.fetch_and_update_weather, daemon=True).start()

        return self.get_state()

    def set_controls(self, req: SimulatorControlRequest) -> VirtualVesselState:
        """Applies driver control changes (speed, throttle, heading, environmental overrides)."""
        with self._lock:
            # Commanded Speed / Throttle
            if req.target_speed_knots is not None:
                max_spd = self.energy_estimator.profile.get("max_speed_knots", 14.5)
                self.state.target_speed_knots = max(0.0, min(req.target_speed_knots, max_spd))
                self.state.speed_through_water_knots = self.state.target_speed_knots
                self.state.throttle_pct = round((self.state.target_speed_knots / max_spd) * 100.0, 1)
            elif req.throttle_pct is not None:
                max_spd = self.energy_estimator.profile.get("max_speed_knots", 14.5)
                self.state.throttle_pct = max(0.0, min(req.throttle_pct, 100.0))
                self.state.target_speed_knots = round((self.state.throttle_pct / 100.0) * max_spd, 1)
                self.state.speed_through_water_knots = self.state.target_speed_knots

            # Commanded Heading
            if req.heading_deg is not None:
                self.state.heading_deg = round(req.heading_deg % 360.0, 1)

            # Environmental Overrides & Mode Handling
            env_override = any(v is not None for v in (req.wave_height_m, req.wind_speed_knots, req.current_speed_knots, req.current_direction_deg))

            if req.environmental_mode == "AUTOMATIC_FORECAST":
                self.state.ocean_conditions.environmental_mode = "AUTOMATIC_FORECAST"
                self.state.ocean_conditions.weather_source = "Open-Meteo API"
                if self.weather_provider is not None:
                    threading.Thread(target=self.fetch_and_update_weather, kwargs={"force": True}, daemon=True).start()
            elif env_override or req.environmental_mode == "MANUAL_SCENARIO":
                self.state.ocean_conditions.environmental_mode = "MANUAL_SCENARIO"
                self.state.ocean_conditions.weather_source = "Manual Scenario Preset"
                self.state.ocean_conditions.weather_freshness = "FRESH"
                now_iso = datetime.now(timezone.utc).isoformat()
                self.state.ocean_conditions.source_timestamp_utc = now_iso
                self.state.ocean_conditions.last_refresh_timestamp_utc = now_iso

            if req.wave_height_m is not None:
                self.state.ocean_conditions.wave_height_m = max(0.0, req.wave_height_m)
            if req.wind_speed_knots is not None:
                self.state.ocean_conditions.wind_speed_knots = max(0.0, req.wind_speed_knots)
            if req.current_speed_knots is not None:
                self.state.ocean_conditions.current_speed_knots = max(0.0, req.current_speed_knots)
            if req.current_direction_deg is not None:
                self.state.ocean_conditions.current_direction_deg = round(req.current_direction_deg % 360.0, 1)

            self.state.timestamp_utc = datetime.now(timezone.utc).isoformat()
            self._recalculate_physics()
            self._publish_frame()
            return self.get_state()

    def update_ocean_conditions(
        self,
        weather_record: NormalizedWeatherRecord,
        source_mode: Optional[str] = None,
    ) -> bool:
        """
        Updates the simulator's ocean conditions from a NormalizedWeatherRecord.
        Guarantees that unavailable (None) fields preserve the last valid value.
        Validates physical ranges before applying.
        Respects manual scenario locks: if environmental_mode is MANUAL_SCENARIO and
        source_mode is not MANUAL_SCENARIO, the update is rejected.
        """
        with self._lock:
            current_mode = self.state.ocean_conditions.environmental_mode
            if current_mode == "MANUAL_SCENARIO" and source_mode != "MANUAL_SCENARIO":
                return False

            oc = self.state.ocean_conditions

            # Map & validate Wind
            if weather_record.wind_speed_knots is not None:
                w_spd = float(weather_record.wind_speed_knots)
                if 0.0 <= w_spd <= 100.0:
                    oc.wind_speed_knots = round(w_spd, 2)
            elif weather_record.wind_speed_ms is not None:
                w_spd = float(weather_record.wind_speed_ms) * 1.94384
                if 0.0 <= w_spd <= 100.0:
                    oc.wind_speed_knots = round(w_spd, 2)

            if weather_record.wind_direction_deg is not None:
                w_dir = float(weather_record.wind_direction_deg)
                if 0.0 <= w_dir <= 360.0:
                    oc.wind_direction_deg = round(w_dir % 360.0, 1)

            # Map & validate Waves
            if weather_record.wave_height_m is not None:
                wv_h = float(weather_record.wave_height_m)
                if 0.0 <= wv_h <= 25.0:
                    oc.wave_height_m = round(wv_h, 2)

            if weather_record.wave_period_s is not None:
                wv_p = float(weather_record.wave_period_s)
                if 0.0 <= wv_p <= 30.0:
                    oc.wave_period_s = round(wv_p, 1)

            if weather_record.wave_direction_deg is not None:
                wv_d = float(weather_record.wave_direction_deg)
                if 0.0 <= wv_d <= 360.0:
                    oc.wave_direction_deg = round(wv_d % 360.0, 1)

            # Map & validate Ocean Currents
            if weather_record.ocean_current_speed_knots is not None:
                c_spd = float(weather_record.ocean_current_speed_knots)
                if 0.0 <= c_spd <= 15.0:
                    oc.current_speed_knots = round(c_spd, 2)

            if weather_record.ocean_current_direction_deg is not None:
                c_dir = float(weather_record.ocean_current_direction_deg)
                if 0.0 <= c_dir <= 360.0:
                    oc.current_direction_deg = round(c_dir % 360.0, 1)

            # Map & validate Atmospheric
            if weather_record.temperature_c is not None:
                t_c = float(weather_record.temperature_c)
                if -50.0 <= t_c <= 60.0:
                    oc.air_temperature_c = round(t_c, 1)

            if weather_record.relative_humidity_pct is not None:
                rh = float(weather_record.relative_humidity_pct)
                if 0.0 <= rh <= 100.0:
                    oc.humidity_pct = round(rh, 1)

            if weather_record.surface_pressure_hpa is not None:
                p_hpa = float(weather_record.surface_pressure_hpa)
                if 800.0 <= p_hpa <= 1100.0:
                    oc.pressure_hpa = round(p_hpa, 1)

            if weather_record.precipitation_mm_per_hr is not None:
                precip = float(weather_record.precipitation_mm_per_hr)
                if 0.0 <= precip <= 200.0:
                    oc.precipitation_mm = round(precip, 2)

            # Provenance & Metadata
            oc.provenance = weather_record.data_type.value if hasattr(weather_record.data_type, "value") else str(weather_record.data_type)
            oc.weather_source = weather_record.data_source
            oc.source_timestamp_utc = weather_record.timestamp_utc
            now_iso = datetime.now(timezone.utc).isoformat()
            oc.last_refresh_timestamp_utc = now_iso

            # Freshness calculation based on record validity timestamp
            try:
                rec_dt = datetime.fromisoformat(weather_record.timestamp_utc)
                if rec_dt.tzinfo is None:
                    rec_dt = rec_dt.replace(tzinfo=timezone.utc)
                now_dt = datetime.now(timezone.utc)
                age = abs((now_dt - rec_dt).total_seconds())
                if age > 7200.0:
                    oc.weather_freshness = "STALE"
                else:
                    oc.weather_freshness = "FRESH"
            except Exception:
                oc.weather_freshness = "FRESH"

            if source_mode is not None:
                oc.environmental_mode = source_mode
            elif oc.environmental_mode != "MANUAL_SCENARIO":
                oc.environmental_mode = "AUTOMATIC_FORECAST"

            self._recalculate_physics()
            self._update_evaluations()
            return True

    def fetch_and_update_weather(self, force: bool = False) -> bool:
        """
        Non-blocking fetch of current weather from the configured weather provider.
        Updates ocean conditions if in AUTOMATIC_FORECAST mode.
        If fetch fails, retains existing conditions and sets freshness to DEGRADED.
        """
        if self.weather_provider is None:
            return False

        with self._lock:
            mode = self.state.ocean_conditions.environmental_mode
            if mode == "MANUAL_SCENARIO" and not force:
                return False
            lat = self.state.latitude
            lon = self.state.longitude

        try:
            record = self.weather_provider.get_current_weather(latitude=lat, longitude=lon)
            if record:
                return self.update_ocean_conditions(record, source_mode="AUTOMATIC_FORECAST")
        except Exception:
            # Weather fetch failed: retain last valid environmental state, mark degraded
            with self._lock:
                self.state.ocean_conditions.weather_freshness = "DEGRADED"
                self._update_evaluations()
            return False
        return False

    def _weather_refresh_loop(self) -> None:
        """Periodic background thread refreshing weather every weather_refresh_interval_seconds or on displacement."""
        while not self._stop_event.is_set():
            try:
                now_mono = time.monotonic()
                should_refresh = False
                with self._lock:
                    mode = self.state.ocean_conditions.environmental_mode
                    if mode != "MANUAL_SCENARIO" and self.weather_provider is not None:
                        if self._last_weather_fetch_mono is None or (now_mono - self._last_weather_fetch_mono) >= self.weather_refresh_interval_seconds:
                            should_refresh = True
                        elif self._last_weather_coords is not None:
                            d_lat = abs(self.state.latitude - self._last_weather_coords[0])
                            d_lon = abs(self.state.longitude - self._last_weather_coords[1])
                            if d_lat >= 0.01 or d_lon >= 0.01:  # Approx 0.6 NM displacement
                                should_refresh = True

                if should_refresh:
                    success = self.fetch_and_update_weather()
                    if success:
                        self._last_weather_fetch_mono = now_mono
                        with self._lock:
                            self._last_weather_coords = (self.state.latitude, self.state.longitude)
            except Exception:
                pass

            # Sleep in responsive slices
            for _ in range(50):
                if self._stop_event.is_set():
                    break
                time.sleep(0.1)

    def update_controls(self, req: SimulatorControlRequest) -> VirtualVesselState:
        """Alias for set_controls."""
        return self.set_controls(req)

    def _recalculate_physics(self) -> None:
        """Recalculates velocity vectors, hydrodynamic resistance, power, and Signal Agent state."""
        stw = self.state.speed_through_water_knots
        heading = self.state.heading_deg
        curr_spd = self.state.ocean_conditions.current_speed_knots
        curr_dir = self.state.ocean_conditions.current_direction_deg

        # Kinematics: Ship velocity vector + Ocean current vector -> Ground velocity (SOG & COG)
        rad_h = math.radians(heading)
        v_sx = stw * math.sin(rad_h)
        v_sy = stw * math.cos(rad_h)

        rad_c = math.radians(curr_dir)
        v_cx = curr_spd * math.sin(rad_c)
        v_cy = curr_spd * math.cos(rad_c)

        v_gx = v_sx + v_cx
        v_gy = v_sy + v_cy

        sog = math.sqrt(v_gx * v_gx + v_gy * v_gy)
        cog = (math.degrees(math.atan2(v_gx, v_gy)) + 360.0) % 360.0

        self.state.speed_over_ground_knots = round(sog, 2)
        self.state.course_over_ground_deg = round(cog, 1)

        # Hydrodynamics & Fuel
        wx_record = NormalizedWeatherRecord(
            weather_id="ENV_VIRTUAL",
            data_source=self.state.ocean_conditions.weather_source,
            latitude=self.state.latitude,
            longitude=self.state.longitude,
            timestamp_utc=self.state.ocean_conditions.source_timestamp_utc or datetime.now(timezone.utc).isoformat(),
            wind_speed_knots=self.state.ocean_conditions.wind_speed_knots,
            wind_direction_deg=self.state.ocean_conditions.wind_direction_deg,
            wave_height_m=self.state.ocean_conditions.wave_height_m,
            wave_period_s=self.state.ocean_conditions.wave_period_s,
            wave_direction_deg=self.state.ocean_conditions.wave_direction_deg,
            temperature_c=self.state.ocean_conditions.air_temperature_c,
            humidity_pct=self.state.ocean_conditions.humidity_pct,
            pressure_hpa=self.state.ocean_conditions.pressure_hpa,
            data_type=WeatherProvenanceType.FORECAST,
        )

        hydro = self.energy_estimator.calculate_hydrodynamics(speed_knots=stw, weather=wx_record)
        self.state.shaft_power_kw = hydro["p_shaft_kw"]
        p_demand = hydro.get("p_shaft_demand_kw", hydro["p_shaft_kw"])
        self.state.shaft_power_demand_kw = p_demand
        self.state.total_power_kw = hydro["p_total_kw"]
        self.state.fuel_consumption_rate_lph = hydro["fuel_rate_lph"]

        # Engine RPM & Load
        max_spd = float(self.energy_estimator.profile.get("max_speed_knots", 14.5))
        p_rated = float(self.energy_estimator.profile.get("engine_power_kw", 4500.0))
        self.state.rated_engine_power_kw = p_rated
        self.state.engine_rpm = round(650.0 + (stw / max_spd) * 1150.0, 0)
        # Engine MCR load % reflects actual required shaft power demand relative to rated continuous rating
        self.state.engine_load_pct = round((p_demand / max(1.0, p_rated)) * 100.0, 1)

        self._update_evaluations()

    def step(self, dt_seconds: float = 1.0) -> VirtualVesselState:
        """
        Executes one deterministic simulation step:
          1. Calculates ocean current drift vector effect on Ground Speed (SOG) & Course (COG).
          2. Advances dead reckoning geographic position (latitude, longitude).
          3. Computes hydrodynamic resistance (calm, wind, wave) and shaft power demand.
          4. Integrates fuel consumption and battery clean energy storage over dt.
          5. Updates voyage distance remaining, progress, and dynamic ETA.
          6. Runs Signal Agent decision-support interpreter.
          7. Publishes canonical frame to TelemetryGateway.
        """
        with self._lock:
            if self.state.status != SimulationStatus.RUNNING:
                return self.get_state()

            self.state.timestamp_utc = datetime.now(timezone.utc).isoformat()
            self._recalculate_physics()

            sog = self.state.speed_over_ground_knots
            cog = self.state.course_over_ground_deg

            # 2. Dead Reckoning Position Advancement
            dist_step_nm = (sog * dt_seconds) / 3600.0
            rad_cog = math.radians(cog)
            rad_lat = math.radians(self.state.latitude)

            delta_lat = (dist_step_nm * math.cos(rad_cog)) / 60.0
            cos_lat = math.cos(rad_lat)
            delta_lon = (dist_step_nm * math.sin(rad_cog)) / (60.0 * max(0.01, cos_lat))

            self.state.latitude = round(self.state.latitude + delta_lat, 6)
            self.state.longitude = round(self.state.longitude + delta_lon, 6)

            # Route progression
            self.state.distance_travelled_nm = round(self.state.distance_travelled_nm + dist_step_nm, 5)
            self.state.distance_remaining_nm = max(0.0, round(self.state.total_distance_nm - self.state.distance_travelled_nm, 4))
            self.state.route_progress_pct = min(100.0, round((self.state.distance_travelled_nm / self.state.total_distance_nm) * 100.0, 3))

            self.state.voyage_elapsed_seconds += int(dt_seconds)
            h = self.state.voyage_elapsed_seconds // 3600
            m = (self.state.voyage_elapsed_seconds % 3600) // 60
            s = self.state.voyage_elapsed_seconds % 60
            self.state.voyage_elapsed_formatted = f"{h:02d}:{m:02d}:{s:02d}"

            # Append to travelled track if moved
            last_pt = self.state.travelled_track[-1] if self.state.travelled_track else [5.58, 5.18]
            if abs(self.state.latitude - last_pt[0]) > 0.0001 or abs(self.state.longitude - last_pt[1]) > 0.0001:
                self.state.travelled_track.append([self.state.latitude, self.state.longitude])
                if len(self.state.travelled_track) > 500:
                    self.state.travelled_track = self.state.travelled_track[::2]

            # Fuel Burn Integration
            fuel_step_liters = (self.state.fuel_consumption_rate_lph * dt_seconds) / 3600.0
            self.state.fuel_consumed_liters = round(self.state.fuel_consumed_liters + fuel_step_liters, 4)
            self.state.fuel_remaining_liters = max(0.0, round(self.state.fuel_remaining_liters - fuel_step_liters, 4))

            # Battery & Solar Integration
            solar_power = 14.2
            hotel_load = self.energy_estimator.auxiliary_hotel_load_kw
            p_net_battery = solar_power - hotel_load  # negative = discharging
            self.state.solar_power_kw = solar_power
            self.state.battery_power_kw = round(p_net_battery, 2)

            delta_kwh = (p_net_battery * dt_seconds) / 3600.0
            batt_cap = self.energy_estimator.battery_capacity_kwh
            self.state.battery_energy_kwh = min(batt_cap, max(0.0, round(self.state.battery_energy_kwh + delta_kwh, 2)))
            self.state.battery_soc_pct = round((self.state.battery_energy_kwh / batt_cap) * 100.0, 1)

            # ETA & Signal Agent Update
            self._update_evaluations()

            # Broadcast to Gateway
            self._publish_frame()

            return self.get_state()

    def _update_evaluations(self) -> None:
        """Evaluates ETA and executes Signal Agent decision logic."""
        sog = self.state.speed_over_ground_knots
        dist_rem = self.state.distance_remaining_nm

        # ETA Calculation
        if sog >= 0.5 and dist_rem > 0:
            hrs = dist_rem / sog
            now_dt = datetime.now(timezone.utc)
            eta_dt = now_dt + timedelta(hours=hrs)
            self.state.eta_utc = eta_dt.isoformat()
            eta_str = eta_dt.strftime("%H:%M UTC (%d %b)")
        else:
            self.state.eta_utc = None
            eta_str = "Stationary / Paused"

        # Signal Agent Decision Rules
        hs = self.state.ocean_conditions.wave_height_m
        w_spd = self.state.ocean_conditions.wind_speed_knots
        fuel_rem = self.state.fuel_remaining_liters
        fuel_rate = self.state.fuel_consumption_rate_lph

        # Calculate fuel needed to destination (with 15% safety margin)
        hrs_to_dest = dist_rem / max(1.0, sog)
        fuel_needed_dest = fuel_rate * hrs_to_dest * 1.15
        range_nm = (fuel_rem / max(1.0, fuel_rate)) * sog if fuel_rate > 0 else 999.0

        if fuel_rem < 500.0:
            self.state.signal_agent = SignalAgentAdvisory(
                status="FUEL_ALERT",
                severity="CRITICAL",
                headline="🚨 CRITICAL FUEL ALERT: Bunker Level Below Reserve (< 500 L)",
                details=[
                    f"Bunker fuel remaining: {fuel_rem:,.0f} L (Emergency threshold: 500 L)",
                    "Immediate bunkering or drastic speed reduction required to prevent fuel starvation.",
                    "HUMAN REVIEW REQUIRED",
                ],
                human_review_required=True,
            )
        elif self.state.shaft_power_demand_kw > self.state.rated_engine_power_kw or self.state.engine_load_pct > 100.0:
            p_demand = self.state.shaft_power_demand_kw
            p_rated = self.state.rated_engine_power_kw
            self.state.signal_agent = SignalAgentAdvisory(
                status="ENGINE_OVERLOAD",
                severity="WARNING",
                headline=f"⚠️ ENGINE OVERLOAD: Shaft Power Demand ({p_demand:.0f} kW) Exceeds Rated MCR ({p_rated:.0f} kW)",
                details=[
                    f"Operating speed: {sog:.1f} kn (Design continuous rating: 12.0 kn, Max: 14.5 kn)",
                    f"Shaft power demand: {p_demand:.0f} kW ({self.state.engine_load_pct:.1f}% MCR load).",
                    f"Delivered power capped at continuous rating ({self.state.shaft_power_kw:.0f} kW).",
                    "Continuous operation above 100% MCR causes thermal and mechanical fatigue.",
                    "Recommend easing propulsion throttle to design service speed (12.0 kn).",
                    "HUMAN REVIEW REQUIRED",
                ],
                human_review_required=True,
            )
        elif hs >= 2.5 or w_spd >= 25.0:
            details_list = [
                f"Significant wave height: {hs:.1f} m (Adverse threshold: 2.5 m)",
                f"Sustained wind speed: {w_spd:.1f} kn (Adverse threshold: 25.0 kn)",
                f"Hydrodynamic resistance elevated; shaft power demand at {self.state.shaft_power_demand_kw:.0f} kW ({self.state.engine_load_pct:.1f}% MCR).",
                f"Fuel burn rate increased to {fuel_rate:.1f} L/h.",
                "Recommend reducing transit speed to ease vessel slamming and maintain fuel margin.",
                "HUMAN REVIEW REQUIRED",
            ]
            self.state.signal_agent = SignalAgentAdvisory(
                status="WEATHER_ALERT",
                severity="WARNING",
                headline="⚠ WEATHER ALERT: Rough Sea / High Wind Zone Encountered",
                details=details_list,
                human_review_required=True,
            )
        elif fuel_rem < fuel_needed_dest and dist_rem > 10.0:
            self.state.signal_agent = SignalAgentAdvisory(
                status="FUEL_ALERT",
                severity="WARNING",
                headline="⚠ FUEL ALERT: Projected Bunker Margin Deficit to Destination",
                details=[
                    f"Bunker fuel remaining: {fuel_rem:,.0f} L",
                    f"Estimated fuel required to destination: {fuel_needed_dest:,.0f} L",
                    f"Range at current speed ({sog:.1f} kn): {range_nm:.1f} NM (Destination distance: {dist_rem:.1f} NM)",
                    "Recommend reducing cruising speed to lower SFOC and fuel consumption.",
                    "HUMAN REVIEW REQUIRED",
                ],
                human_review_required=True,
            )
        elif self.state.battery_soc_pct < 20.0:
            self.state.signal_agent = SignalAgentAdvisory(
                status="BATTERY_ALERT",
                severity="NOTICE",
                headline="ℹ BATTERY ALERT: Battery SOC Below Reserve Threshold (< 20%)",
                details=[
                    f"Current Battery State of Charge: {self.state.battery_soc_pct:.1f}%",
                    "Auxiliary hotel load supported by main diesel generator.",
                    "Solar array generation active at climatological daylight rate.",
                    "HUMAN REVIEW REQUIRED",
                ],
                human_review_required=True,
            )
        else:
            self.state.signal_agent = SignalAgentAdvisory(
                status="NORMAL",
                severity="INFO",
                headline="NORMAL: Vessel Operating Within Nominal Parameters",
                details=[
                    f"Speed: {sog:.1f} kn (STW: {self.state.speed_through_water_knots:.1f} kn) | Heading: {self.state.heading_deg:.0f}°",
                    f"Fuel Remaining: {fuel_rem:,.0f} L (Burn rate: {fuel_rate:.1f} L/h | Consumed: {self.state.fuel_consumed_liters:,.1f} L)",
                    f"Distance to Lagos: {dist_rem:.1f} NM | Progress: {self.state.route_progress_pct:.1f}%",
                    f"Ocean Conditions: Wind {w_spd:.1f} kn, Waves {hs:.1f} m, Current {self.state.ocean_conditions.current_speed_knots:.1f} kn",
                    f"Estimated Arrival: {eta_str}",
                    "All hydrodynamic, propulsion, clean energy, and environmental metrics normal.",
                    "HUMAN REVIEW REQUIRED",
                ],
                human_review_required=True,
            )

    def _publish_frame(self) -> None:
        """Constructs canonical telemetry payload and updates the TelemetryGateway."""
        if not self.gateway:
            return
        if self.state.status != SimulationStatus.RUNNING:
            return

        now_iso = datetime.now(timezone.utc).isoformat()
        is_running = self.state.status == SimulationStatus.RUNNING

        payload = CanonicalTelemetryPayload(
            telemetry_id="VIRTUAL_VESSEL_SIMULATOR_FRAME",
            timestamp_utc=now_iso,
            ingested_at_utc=now_iso,
            vessel_id=self.state.vessel_id,
            position=PositionTelemetry(
                latitude=self.state.latitude,
                longitude=self.state.longitude,
                speed_over_ground_knots=self.state.speed_over_ground_knots,
                course_over_ground_deg=self.state.course_over_ground_deg,
                heading_deg=self.state.heading_deg,
            ),
            engine=EngineTelemetry(
                state=EngineOperationalState.ON if is_running else EngineOperationalState.OFF,
                rpm=self.state.engine_rpm if is_running else 0.0,
                load_percent=min(100.0, self.state.engine_load_pct) if is_running else 0.0,
                power_kw=self.state.shaft_power_kw if is_running else 0.0,
                fuel_rate_lph=self.state.fuel_consumption_rate_lph if is_running else 0.0,
            ),
            energy=EnergyTelemetry(
                fuel_remaining_liters=self.state.fuel_remaining_liters,
                fuel_rate_lph=self.state.fuel_consumption_rate_lph if is_running else 0.0,
                battery_soc_pct=self.state.battery_soc_pct,
                battery_soh_pct=98.5,
                battery_usable_kwh=self.state.battery_energy_kwh,
                battery_power_kw=self.state.battery_power_kw if is_running else 0.0,
                solar_power_kw=self.state.solar_power_kw,
            ),
            quality=TelemetryQuality(
                overall=TelemetryQualityState.VALID,
                freshness=TelemetryFreshnessState.FRESH,
                freshness_age_seconds=0.0,
            ),
            provenance=TelemetryProvenance(
                source="VIRTUAL_VESSEL_SIMULATOR",
                mode=TelemetryProvenanceType.SIMULATED,
                stream_id="NATIVE_SIMULATOR_STREAM",
            ),
        )

        try:
            self.gateway.ingest_canonical(payload)
        except Exception:
            pass

    def _run_loop(self) -> None:
        """Continuous background simulation thread stepping every 1.0 second."""
        while not self._stop_event.is_set():
            try:
                if self.state.status == SimulationStatus.RUNNING:
                    self.step(dt_seconds=1.0)
            except Exception:
                pass
            # Responsive sleep slices
            for _ in range(10):
                if self._stop_event.is_set():
                    break
                time.sleep(0.1)

    def get_state(self) -> VirtualVesselState:
        """Returns the current VirtualVesselState."""
        with self._lock:
            return self.state.model_copy(deep=True)


