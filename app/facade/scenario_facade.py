class FacadeError(Exception):
    """Base exception class for all facade errors."""
    pass


class FacadeValidationError(FacadeError):
    """Raised when an application-level request fails validation."""
    pass


class FacadeExecutionError(FacadeError):
    """Raised when an underlying frozen execution raises an error."""
    pass


class MaritimeScenarioFacade:
    """
    High-level facade orchestrator for the Maritime Clean Energy Simulation Core.
    Acts as an immutable adapter layer between external interfaces and frozen Phase 0–9 logic.
    """

    def __init__(self, frozen_core_version: str = "1.0.0"):
        self.frozen_core_version = frozen_core_version

    # ==========================================================================
    # 1. Single-Voyage Simulation
    # ==========================================================================
    def simulate_voyage(
        self,
        request: SimulateVoyageRequest,
    ) -> FacadeResponse[Phase6SimulationResult]:
        """
        Execute single-voyage hydrodynamic, electrical balance, and regulatory simulation.
        Delegates to Phase 6 Gateway without modifying physics or emissions logic.
        """
        try:
            p6_req = VoyageSimulationRequest(
                ship_type=request.ship_type,
                route_id=request.route_id,
                month=request.month,
                speed_knots=request.speed_knots,
                distance_nm=request.distance_nm,
                solar_area_m2=request.solar_area_m2,
                battery_capacity_kwh=request.battery_capacity_kwh,
                fuel_price_usd_per_mt=request.fuel_price_usd_per_mt,
                carbon_price_usd_per_mt=request.carbon_price_usd_per_mt,
                daily_ghi_kwh_per_m2=request.daily_ghi_kwh_per_m2,
                regulatory_year=request.regulatory_year,
            )
            result = _frozen_simulate_voyage(p6_req)

            provenance = FacadeProvenanceMetadata(
                operation=FacadeOperationEnum.SIMULATE_VOYAGE,
                underlying_phase="Phase 6",
                underlying_function="phase6_gateway.simulate_voyage",
                frozen_core_version=self.frozen_core_version,
                vessel_id=request.ship_type,
            )
            return FacadeResponse(provenance=provenance, data=result)
        except Exception as e:
            raise FacadeExecutionError(f"Simulation failed in Phase 6 Gateway: {str(e)}") from e

    # ==========================================================================
    # 2. Single Sizing Candidate Evaluation
    # ==========================================================================
    def evaluate_sizing_candidate(
        self,
        request: EvaluateSizingCandidateRequest,
    ) -> FacadeResponse[OptimizationCandidate]:
        """
        Evaluate a single sizing candidate (Apv, Ebatt) under Phase 8 physical and economic rules.
        """
        try:
            opt_params = OptimizationParameters(
                ship_type=request.ship_type,
                annual_voyages=request.annual_voyages,
                discount_rate=request.discount_rate,
                fuel_price_usd_per_l=request.fuel_price_usd_per_l,
                carbon_price_usd_per_tonne=request.carbon_price_usd_per_tonne,
                analysis_horizon_years=request.analysis_horizon_years,
            )
            cand = _frozen_evaluate_single_sizing_candidate(
                solar_area_m2=request.solar_area_m2,
                battery_capacity_kwh=request.battery_capacity_kwh,
                params=opt_params,
                deck_area_limit_m2=request.deck_area_limit_m2,
                battery_weight_limit_tonnes=request.battery_weight_limit_tonnes,
                predicted_soh=request.predicted_soh,
                auxiliary_energy_demand_kwh=request.auxiliary_energy_demand_kwh,
                voyage_duration_hours=request.voyage_duration_hours,
                predicted_fuel_consumption_L=request.predicted_fuel_consumption_L,
                predicted_CO2_kg=request.predicted_CO2_kg,
                daily_ghi_kwh_per_m2=request.daily_ghi_kwh_per_m2,
                generator_sfoc_kg_per_kwh=request.generator_sfoc_kg_per_kwh,
                fuel_density_kg_per_l=request.fuel_density_kg_per_l,
                emission_factor_kgco2_per_kgfuel=request.emission_factor_kgco2_per_kgfuel,
            )

            provenance = FacadeProvenanceMetadata(
                operation=FacadeOperationEnum.EVALUATE_SIZING_CANDIDATE,
                underlying_phase="Phase 8",
                underlying_function="phase8_optimizer.evaluate_single_sizing_candidate",
                frozen_core_version=self.frozen_core_version,
                vessel_id=request.ship_type,
            )
            return FacadeResponse(provenance=provenance, data=cand)
        except Exception as e:
            raise FacadeExecutionError(f"Candidate evaluation failed in Phase 8: {str(e)}") from e

    # ==========================================================================
    # 3. Parametric System Sizing Optimization
    # ==========================================================================
    def optimize_system_sizing(
        self,
        request: OptimizeSystemSizingRequest,
    ) -> FacadeResponse[OptimizationResult]:
        """
        Execute full parametric grid sizing search or adapter sizing over a simulation result.
        """
        try:
            opt_params = OptimizationParameters(
                ship_type=request.ship_type,
                min_solar_area_m2=request.min_solar_area_m2,
                max_solar_area_m2=request.max_solar_area_m2,
                step_solar_area_m2=request.step_solar_area_m2,
                min_battery_capacity_kwh=request.min_battery_capacity_kwh,
                max_battery_capacity_kwh=request.max_battery_capacity_kwh,
                step_battery_capacity_kwh=request.step_battery_capacity_kwh,
                objective=request.objective,
                pareto_objectives=request.pareto_objectives,
                budget_limit_usd=request.budget_limit_usd,
                annual_voyages=request.annual_voyages,
                discount_rate=request.discount_rate,
                analysis_horizon_years=request.analysis_horizon_years,
            )

            if request.simulation_result is not None:
                res = _frozen_evaluate_single_voyage_sizing(
                    params=opt_params,
                    simulation_result=request.simulation_result,
                )
            else:
                res = _frozen_optimize_system_sizing(opt_params)

            provenance = FacadeProvenanceMetadata(
                operation=FacadeOperationEnum.OPTIMIZE_SYSTEM_SIZING,
                underlying_phase="Phase 8",
                underlying_function="phase8_optimizer.optimize_system_sizing",
                frozen_core_version=self.frozen_core_version,
                vessel_id=request.ship_type,
            )
            return FacadeResponse(provenance=provenance, data=res)
        except Exception as e:
            raise FacadeExecutionError(f"Optimization failed in Phase 8: {str(e)}") from e

    # ==========================================================================
    # 4. Sensitivity, Break-Even & 2D Grid Analysis (Candidate 1)
    # ==========================================================================
