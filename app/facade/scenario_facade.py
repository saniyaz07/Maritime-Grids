    # ==========================================================================
    # 8. Dossier Assembly & Export (Candidate 5)
    # ==========================================================================
    def export_scenario_dossier(
        self,
        request: DossierExportFacadeRequest,
    ) -> FacadeResponse[Dict[str, Any]]:
        """
        Assemble, validate, and serialize cross-phase scenario dossier via Candidate 5.
        Optionally persists artifacts to disk safely if output_directory is specified.
        """
        try:
            dossier_req = DossierAssemblyRequest(
                scenario_name=request.scenario_name,
                vessel_id=request.vessel_id,
                ship_type=request.ship_type,
                route_id=request.route_id,
                export_formats=request.export_formats,
                phase6_result=request.phase6_result,
                phase7_result=request.phase7_result,
                phase8_result=request.phase8_result,
                candidate1_sensitivity=request.candidate1_sensitivity,
                candidate2_cooptimization=request.candidate2_cooptimization,
                candidate3_portfolio=request.candidate3_portfolio,
                candidate4_trajectory=request.candidate4_trajectory,
            )

            dossier = _frozen_assemble_dossier(dossier_req)
            raw_artifacts = _frozen_export_dossier(dossier_req)

            saved_paths: Dict[str, str] = {}
            if request.output_directory is not None:
                persisted = _frozen_save_dossier_to_disk(
                    artifacts=raw_artifacts,
                    output_directory=request.output_directory,
                    filename_prefix=request.filename_prefix,
                )
                saved_paths = {fmt.value: path for fmt, path in persisted.items()}

            response_data = {
                "dossier": dossier,
                "artifacts": {fmt.value: art for fmt, art in raw_artifacts.items()},
                "saved_paths": saved_paths,
            }

            diag_messages = [f"[{d.severity}] {d.message}" for d in dossier.diagnostics]

            provenance = FacadeProvenanceMetadata(
                operation=FacadeOperationEnum.ASSEMBLE_AND_EXPORT_DOSSIER,
                underlying_phase="Phase 9 Candidate 5",
                underlying_function="phase9_dossier_exporter.export_dossier",
                frozen_core_version=self.frozen_core_version,
                scenario_name=request.scenario_name,
                vessel_id=request.vessel_id,
            )
            return FacadeResponse(provenance=provenance, data=response_data, diagnostics=diag_messages)
        except Exception as e:
            raise FacadeExecutionError(f"Dossier export failed in Candidate 5: {str(e)}") from e
